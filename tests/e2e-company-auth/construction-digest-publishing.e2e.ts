import { randomUUID } from 'node:crypto';
import { expect, test } from '@playwright/test';
import { openDialog } from './dialog';

test('a project manager publishes a durable weekly digest and sees failed delivery without a sender', async ({ page }) => {
  test.setTimeout(180_000);
  const id = randomUUID().slice(0, 8);
  const projectName = `Digest acceptance ${id}`;
  await page.goto('/sign-up');
  await page.getByLabel('Your full name', { exact: true }).fill('Digest acceptance owner');
  await page.getByLabel('Email address', { exact: true }).fill(`digest-owner-${id}@example.test`);
  await page.getByLabel('Company name', { exact: true }).fill(`Digest company ${id}`);
  await page.getByLabel('Password', { exact: true }).fill('Disposable digest acceptance passphrase 2026!');
  await page.getByRole('button', { name: 'Create account & company', exact: true }).click();
  await expect(page).toHaveURL(/\/onboarding$/);
  await page.getByRole('link', { name: 'Set up later', exact: true }).click();

  await page.goto('/construction/projects');
  const newProject = page.getByRole('dialog', { name: 'New project', exact: true });
  await openDialog(page.getByRole('button', { name: 'New project', exact: true }), newProject);
  await newProject.getByLabel('Name', { exact: true }).fill(projectName);
  await newProject.getByLabel('Location', { exact: true }).fill('Lekki, Lagos');
  await newProject.getByRole('combobox', { name: 'Project type', exact: true }).selectOption('residential');
  await newProject.getByLabel('State or region', { exact: true }).fill('Lagos, Nigeria');
  await newProject.getByLabel('Client', { exact: true }).fill('Acceptance client');
  await newProject.getByLabel('Contract (₦)', { exact: true }).fill('25000000');
  await newProject.getByLabel('Budget (₦)', { exact: true }).fill('20000000');
  await newProject.getByLabel('Planned finish', { exact: true }).fill(new Date(Date.now() + 180 * 86400000).toISOString().slice(0, 10));
  await newProject.getByRole('button', { name: 'Create project', exact: true }).click();
  await expect(newProject).not.toBeVisible();
  const projectCard = page.getByRole('heading', { name: projectName, exact: true }).locator('xpath=ancestor::section[1]');
  const setup = await projectCard.getByRole('link', { name: 'Set up project', exact: true }).getAttribute('href');
  const projectId = setup!.split('/')[3];
  await page.goto(`/construction/projects/${projectId}/setup?section=lifecycle`);
  await page.getByLabel('Reason for transition', { exact: true }).fill('Project mobilisation has been approved for the acceptance test.');
  await page.getByRole('button', { name: 'Activate', exact: true }).click();
  await expect(page.getByText('Active', { exact: true }).first()).toBeVisible();
  await page.goto('/construction/digest');
  await expect(page.getByText(projectName, { exact: true }).first()).toBeVisible();
  await page.getByRole('group', { name: 'Select digest project' }).getByRole('button', { name: projectName, exact: true }).click();
  await page.getByRole('button', { name: "I've reviewed the gaps", exact: true }).click();
  await page.getByRole('tab', { name: 'Draft digest', exact: true }).click();
  const recipient = `recipient-${id}@example.test`;
  await page.getByLabel('Recipient email addresses · one per line or comma separated').fill(recipient);
  await page.getByRole('button', { name: 'Review and publish digest', exact: true }).click();
  const confirmation = page.getByRole('dialog', { name: 'Review construction change', exact: true });
  await expect(confirmation).toContainText(recipient);
  await confirmation.getByRole('button', { name: 'Confirm change', exact: true }).click();
  await expect(confirmation).not.toBeVisible();
  await expect(page.getByText('Email sender or delivery callback is not configured.', { exact: false })).toBeVisible();
  await page.reload();
  await expect(page.getByText(recipient, { exact: false })).toBeVisible();
  await expect(page.getByText('Email sender or delivery callback is not configured.', { exact: false })).toBeVisible();
  await page.getByRole('tab', { name: 'Draft digest', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Review and publish digest', exact: true })).toBeDisabled();
});
